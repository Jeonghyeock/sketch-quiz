describe('제시어 목록', () => {
  it('흔한 추측 문장에 목록 단어를 하나 넣으면 다른 목록 단어는 걸리지 않는다', () => {
    const normalizedWords = [...new Set(WORDS.map(normalizeAnswer))];
    const collisions: string[] = [];
    for (const word of WORDS) {
      for (const guess of GUESSES) {
        const text = normalizeAnswer(guess.replaceAll('X', word));
        const others = normalizedWords.filter((w) => w !== normalizeAnswer(word) && text.includes(w));
        if (others.length > 0) collisions.push(`${guess.replaceAll('X', word)} → ${others.join(', ')}`);
      }
    }
    expect(collisions).toEqual([]);
  });
});
